/** Plain verb of `rel` as walked: `inverse` = from the object's side. */
export const plainVerb = (rel: string, inverse: boolean): string =>
  PLAIN[current][inverse ? `${rel}~` : rel] ?? relLabel(rel);
/** One hop as a sentence in plain words, from the side the reader walks (a → b). */
export function hopSentence(rel: string, inverse: boolean, a: string, b: string): string {
  const d = PLAIN[current];
  const tpl = d[`sentence:${rel}${inverse ? "~" : ""}`] ?? d.sentence;
  return tpl.replace("{verb}", plainVerb(rel, inverse)).replace("{a}", a).replace("{b}", b);
}
