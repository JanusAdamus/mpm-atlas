/** UI string, with `{name}` placeholders filled from `vars`. */
/** Keys with a `_one` variant take it when `vars.n` is singular in the active language. */
export function t(key: string, vars: Record<string, string | number> = {}): string {
  const n = Number(vars.n); // callers often pass `n.toLocaleString()`; "1,234" is NaN, i.e. plural
  const one = vars.n !== undefined && Number.isFinite(n) && new Intl.PluralRules(current).select(n) === "one" ? UI[current][`${key}_one`] : undefined;
  const s = one ?? UI[current][key] ?? UI.es[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

